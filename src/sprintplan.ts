export function planFiles(config: Config, sprintName: string): { md: string; json: string; dir: string } {
  const root = ensureDir(resolvePath(config.workspace.sprints_dir));
  const base = path.join(root, `${slug(sprintName)}-plan`);
  return { md: `${base}.md`, json: `${base}.json`, dir: path.join(root, slug(sprintName)) };
}

// dependencies that can't be right, whatever the planner says: on itself, or on a ticket that's merged already
export function dropImpossible(plan: S.SprintPlan, tickets: JiraSummary[], config: Config): string[] {
  const merged = new Set([config.jira.statuses.ready_for_test, ...config.jira.statuses.testing].map((s) => s.toLowerCase()));
  const status = new Map(tickets.map((t) => [t.key, t]));
  const dropped: string[] = [];
  plan.dependencies = plan.dependencies.filter((d) => {
    const parent = status.get(d.depends_on);
    const why = d.ticket === d.depends_on ? "a ticket can't depend on itself" : parent && (parent.done || merged.has(parent.status.toLowerCase())) ? `${d.depends_on} is ${parent.status}, so its code is merged` : '';
    if (why) dropped.push(`${d.ticket} on ${d.depends_on} in ${d.repo}: ${why}`);
    return !why;
  });
  return dropped;
}

export function renderPlan(name: string, p: S.SprintPlan, dropped: string[] = []): string {
  const list = <T>(items: T[], fn: (x: T) => string) => (items.length ? items.map(fn).join('\n') : '- none');
  return [
    `# ${name}: sprint plan`,
    `Generated by \`agent sprint-plan\` on ${new Date().toISOString().slice(0, 10)}. For the developer and the tech lead; nothing here was written to Jira.`,
    `## Summary\n\n${p.summary}`,
    `## Suggested start order\n\n${p.start_order.map((s, i) => `${i + 1}. ${s.ticket}: ${s.why}`).join('\n') || '- none'}`,
    `## Dependencies (build B on A's branch)\n\n${list(p.dependencies, (d) => `- **${d.ticket}** depends on **${d.depends_on}** in ${d.repo}: ${d.reason}`)}${dropped.length ? `\n\nDropped by the checks:\n${dropped.map((x) => `- ${x}`).join('\n')}` : ''}`,
    `## FE ↔ BE pairs\n\n${list(p.fe_be_pairs, (x) => `- ${x.fe} ↔ ${x.be}: ${x.contract}`)}`,
    `## Collision risks\n\n${list(p.collisions, (c) => `- ${c.tickets.join(', ')} (${c.area}): ${c.advice}`)}`,
    `## Build for reuse\n\n${list(p.build_for_reuse, (b) => `- ${b.ticket} → for ${b.for_tickets.join(', ')}: ${b.what}`)}`,
    `## Ticket issues (for the tech lead)\n\n${list(p.ticket_issues, (t) => `- **${t.ticket}**: ${t.problem} Suggestion: ${t.suggestion}`)}`,
  ].join('\n\n');
}

// the parts of a sprint plan that concern one ticket, for that ticket's run
export function adviceFor(config: Config, sprintName: string | undefined, key: string): { text: string; keys: string[] } | null {
  if (!sprintName) return null;
  const { json } = planFiles(config, sprintName);
  if (!fs.existsSync(json)) return null;
  const p = readJson<S.SprintPlan>(json);
  const lines: string[] = [];
  const keys = new Set<string>();
  for (const d of p.dependencies) {
    if (d.ticket === key) {
      lines.push(`- Depends on ${d.depends_on} in ${d.repo}: ${d.reason}`);
      keys.add(d.depends_on);
    }
    if (d.depends_on === key) {
      lines.push(`- ${d.ticket} will be built on this ticket in ${d.repo}: ${d.reason}`);
      keys.add(d.ticket);
    }
  }
  for (const x of p.fe_be_pairs) {
    if (x.fe === key || x.be === key) {
      lines.push(`- FE/BE pair ${x.fe} ↔ ${x.be}: ${x.contract}`);
      keys.add(x.fe === key ? x.be : x.fe);
    }
  }
  for (const c of p.collisions.filter((c) => c.tickets.includes(key))) {
    const others = c.tickets.filter((t) => t !== key);
    lines.push(`- Collision risk with ${others.join(', ')} (${c.area}): ${c.advice}`);
    // read the tickets we may clash with, so the plan can avoid it
    others.forEach((t) => keys.add(t));
  }
  for (const b of p.build_for_reuse) {
    if (b.ticket === key) lines.push(`- Build for reuse by ${b.for_tickets.join(', ')}: ${b.what}`);
    if (b.for_tickets.includes(key)) lines.push(`- ${b.ticket} builds something this ticket should reuse: ${b.what}`);
  }
  for (const t of p.ticket_issues.filter((t) => t.ticket === key)) lines.push(`- Known issue with this ticket: ${t.problem} (${t.suggestion})`);
  keys.delete(key);
  if (!lines.length) return null;
  return { text: `# Sprint plan advice for ${key} (${sprintName})\n\nFrom the sprint-wide analysis the developer ran at the start of the sprint. Strong advice: weigh it against the ticket and the code.\n\n${lines.join('\n')}\n`, keys: [...keys] };
}

export async function runSprintPlan(config: Config, jira: Jira, opts: { key?: string; profile?: string; set?: string[] }): Promise<{ md: string; costUsd: number }> {
  // the sprint comes from a ticket in it, or from the project's open sprint
  const anchorKey = opts.key ?? (await jira.search(`project = ${config.jira.project} AND sprint in openSprints() ORDER BY key DESC`, 1))[0]?.key;
  if (!anchorKey) throw new Error(`No open sprint found for project ${config.jira.project}`);
  const anchor = await jira.getIssue(anchorKey);
  const sprint = anchor.sprints.find((s) => s.state === 'active') ?? anchor.sprints.at(-1);
  if (!sprint) throw new Error(`${anchorKey} is not in a sprint`);
  const files = planFiles(config, sprint.name);
  const ticketsDir = ensureDir(path.join(files.dir, 'tickets'));

  log(`reading ${sprint.name}`);
  const tickets = await jira.search(`sprint = ${sprint.id} ORDER BY key`);
  for (const t of tickets) writeText(path.join(ticketsDir, `${t.key}.md`), ticketMarkdown(await jira.getIssue(t.key)));
  const ctx = await buildSprintContext({ config, jira, issue: anchor, key: anchorKey, ticketText: '', relatedDir: path.join(files.dir, 'related'), forcedRelated: [], ownRuns: [] });

  const repoKeys = Object.keys(config.repos).filter((k) => config.repos[k].path && fs.existsSync(repoPath(config, k)));
  const repos = repoKeys.map((k) => `  - ${k} (${config.repos[k].kind}): ${config.repos[k].description}. \`${repoPath(config, k)}\``).join('\n');
  const schema = S.sprintPlanFor((repoKeys.length ? repoKeys : Object.keys(config.repos)) as [string, ...string[]]);
  log(`analysing ${tickets.length} tickets`);
  const model = resolvePlanner(config, opts.profile, opts.set);
  log(`  planner: ${model.provider}${model.model ? ':' + model.model : ''}${model.effort ? ' (' + model.effort + ')' : ''}`);
  const result = await runAgent({
    role: 'planner',
    step: 'sprint-plan',
    model,
    cwd: files.dir,
    prompt: render(fs.readFileSync(path.join(TOOL_ROOT, 'prompts', 'sprint-plan.md'), 'utf8'), { sprint: sprint.name, ticketsDir, mapFile: ctx.sprintFile ?? 'not available', repos }),
    access: 'read',
    writableDirs: [],
    readDirs: [files.dir, ...repoKeys.map((k) => repoPath(config, k))],
    schema: S.jsonSchema(schema),
    timeoutMs: config.limits.agent_timeout_min * 60_000,
    logDir: path.join(files.dir, 'logs'),
  });
  const plan = schema.parse(result.structured);
  const dropped = dropImpossible(plan, tickets, config);
  writeJson(files.json, plan);
  writeText(files.md, renderPlan(sprint.name, plan, dropped));
  return { md: files.md, costUsd: result.costUsd ?? 0 };
}
